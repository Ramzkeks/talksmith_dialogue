local function languageTable()
    local language = TS.Config and TS.Config.language or "en"
    return TS.Localization.IntegrationText[language] or TS.Localization.IntegrationText.en
end

function TS.Localization.Integration(key, ...)
    local text = languageTable()[key] or TS.Localization.IntegrationText.en[key] or key
    if select("#", ...) > 0 then
        return string.format(text, ...)
    end

    return text
end

function TS.Localization.IntegrationCategory(id)
    local text = languageTable()
    return text.categories[id] or TS.Localization.IntegrationText.en.categories[id] or id
end

function TS.Localization.IntegrationCapability(id)
    local text = languageTable()
    return text.capabilities[id] or TS.Localization.IntegrationText.en.capabilities[id] or id
end

function TS.Localization.IntegrationParameter(id)
    local text = languageTable()
    return text.params[id] or TS.Localization.IntegrationText.en.params[id]
end

function TS.Localization.IntegrationReference(id, kind, field, fallback)
    if TS.Localization.ReferenceTextFor then
        local exact = TS.Localization.ReferenceTextFor(id, kind, field)
        if exact ~= nil then
            return exact
        end
    end

    local integrationID, localID = string.match(id or "", "^([^.]+)%.(.+)$")
    if not integrationID or not localID then
        return fallback or id
    end

    local text = languageTable()
    local labels = text[kind .. "s"] or {}
    local label = labels[localID]
    if not label then
        return fallback or id
    end

    local manifest = TS.Integrations and TS.Integrations.Registry[integrationID]
    if not manifest and TS.Editor.Catalog and TS.Editor.Catalog.integrations then
        manifest = TS.Editor.Catalog.integrations[integrationID]
    end
    local addonName = manifest and manifest.name
        or integrationID == "inventory" and TS.Localization.Integration("generic_inventory")
        or integrationID == "currency" and TS.Localization.Integration("generic_currency")
        or integrationID == "core" and "Talksmith"
        or integrationID == "darkrp" and "DarkRP"
        or integrationID

    if field == "description" then
        return TS.Localization.Integration("ref_" .. kind .. "_description", label, addonName)
    end

    return label
end
