function TS.L(key, ...)
    local lang = TS.Config.language
    local s = (TS.Localization.Text[lang] or TS.Localization.Text.en)[key] or TS.Localization.Text.en[key] or key
    if select("#", ...) > 0 then
        return string.format(s, ...)
    end
    return s
end

local function refLangTable(name)
    local lang = TS.Config and TS.Config.language or "en"
    local t = TS.Localization.Text[lang] or TS.Localization.Text.en
    return t[name] or TS.Localization.Text.en[name] or {}
end

function TS.Localization.ReferenceName(id, fallback)
    return refLangTable("ref_labels")[id] or fallback or id
end

function TS.Localization.ReferenceParameter(key, fallback, integration)
    local integrationLabel = integration
        and TS.Localization.IntegrationParameter
        and TS.Localization.IntegrationParameter(key)
    return integrationLabel
        or refLangTable("ref_params")[key]
        or (TS.Localization.IntegrationParameter and TS.Localization.IntegrationParameter(key))
        or fallback
        or key
end

function TS.Localization.ReferenceHint(key)
    return refLangTable("ref_param_hints")[key]
end
